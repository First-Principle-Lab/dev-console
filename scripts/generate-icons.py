#!/usr/bin/env python3
"""Generate the native shell's icon set from the Lucide icons the Svelte frontend draws.

`src/components/Icon.svelte` maps each `IconName` to a `@lucide/svelte` component and draws it at
stroke width 1.75. This script reads the same Lucide icon data from `node_modules` and writes it as
`rune::Icon` statics into `crates/dev-console-desktop/src/icons.rs`, so both shells draw the same
paths. Run it after a Lucide upgrade:

  python3 scripts/generate-icons.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / "node_modules" / "@lucide" / "svelte" / "dist" / "icons"
OUT = ROOT / "crates" / "dev-console-desktop" / "src" / "icons.rs"

# IconName -> Lucide file, as `src/components/Icon.svelte` maps them, plus the few the native
# shell draws that the web takes from elsewhere (the eye-off toggle and the external link).
NAMES = {
    "command": "terminal",
    "collection": "list",
    "inbox": "inbox",
    "secret": "key-round",
    "lock": "lock-keyhole",
    "unlock": "lock-keyhole-open",
    "copy": "copy",
    "reveal": "eye",
    "hide": "eye-off",
    "edit": "pencil",
    "pin": "pin",
    "unpin": "pin-off",
    "run": "play",
    "trash": "trash-2",
    "folder": "folder-open",
    "search": "search",
    "plus": "plus",
    "back": "arrow-left",
    "alert": "triangle-alert",
    "check": "check",
    "shield": "shield",
    "gear": "settings",
    "update": "refresh-cw",
    "project": "folder-git-2",
    "history": "history",
    "close": "x",
    "chevron": "chevron-down",
    "external": "external-link",
    # Native-only: the sidebar's quiet actions.
    "import": "folder-input",
    "environment": "file-key",
    "terminal": "square-terminal",
    "more": "ellipsis",
}

DATA = re.compile(r"__iconData\s*=\s*(\{.*?\});", re.S)


def body(node: list) -> str:
    parts = []
    for tag, attrs in node:
        rendered = " ".join(f'{k}="{v}"' for k, v in attrs.items() if k != "key")
        parts.append(f"<{tag} {rendered}/>")
    inner = "".join(parts)
    return (
        '<g fill="none" stroke="currentColor" stroke-width="1.75" '
        f'stroke-linecap="round" stroke-linejoin="round">{inner}</g>'
    )


def main() -> int:
    if not ICONS.is_dir():
        print(f"missing {ICONS}; run `bun install` first", file=sys.stderr)
        return 1
    out = [
        "//! Generated by scripts/generate-icons.py from the Lucide icons `src/components/Icon.svelte`",
        "//! draws. Do not edit.",
        "use rune::Icon;",
        "",
    ]
    for name, lucide in NAMES.items():
        path = ICONS / f"{lucide}.svelte"
        if not path.exists():
            # Lucide keeps renamed icons as `.js` aliases that re-export the current file.
            alias = re.search(r'from "\./(.+?\.svelte)"', (ICONS / f"{lucide}.js").read_text())
            path = ICONS / alias.group(1)
        source = path.read_text()
        match = DATA.search(source)
        if not match:
            print(f"no icon data in {lucide}.svelte", file=sys.stderr)
            return 1
        data = json.loads(match.group(1))
        out += [
            f"pub static {name.upper()}: Icon = Icon {{",
            f'    name: "{name}",',
            f"    view: {float(data['size'])},",
            f'    body: r#"{body(data["node"])}"#,',
            "};",
        ]
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {len(NAMES)} icons to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
